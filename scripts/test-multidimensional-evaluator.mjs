import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { annotationsToLabels, boundsFromObj } from './generate-artifacts.mjs';
import { MULTI_VIEW_NAMES, buildDepthGrid, evaluateLayout, parseObjTriangles } from '../lib/layout-optimizer.mjs';
import { triangleIntersectsLabelBox } from '../lib/mesh-label-intersection.mjs';
import { layoutFeatureVector } from '../lib/preference-model.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cleanFile = path.join(root, 'experiments', 'artifacts', 'round1', 'test', 'Lamp', '17343', '17343_clean.obj');
const annotationFile = path.join(root, 'data', 'Layout', 'Lamp', '17343', 'layout1', 'Annotation', '17343.json');
const clean = await fs.readFile(cleanFile, 'utf8');
const annotation = JSON.parse(await fs.readFile(annotationFile, 'utf8'));
const bounds = boundsFromObj(clean);
const geometry = parseObjTriangles(clean);
const depthGrids = Object.fromEntries(MULTI_VIEW_NAMES.map((view) => [view, buildDepthGrid(geometry, bounds, view, 128)]));
const manual = annotationsToLabels(annotation);
const manualMetrics = evaluateLayout(manual, bounds, { viewPolicy: 'binocular', depthGrids, manualReference: manual });
assert.equal(manualMetrics.camera_protocol, 'dataset_multiview_reproduction_v1');
assert.equal(manualMetrics.manual_similarity.manual_center_distance_norm, 0);
assert.equal(manualMetrics.manual_similarity.manual_style_distance, 0);
const withoutTarget = evaluateLayout(manual, bounds, { viewPolicy: 'binocular', depthGrids });
assert.equal(manualMetrics.intrinsic_quality_score, withoutTarget.intrinsic_quality_score, 'intrinsic reward quality cannot depend on manual reference');
assert.deepEqual(layoutFeatureVector(manualMetrics), layoutFeatureVector(withoutTarget), 'reward inputs cannot contain manually adjusted test targets');
assert.ok(manualMetrics.text_pixel_height > 0);
assert.ok(manualMetrics.text_fit_ratio >= 0 && manualMetrics.text_fit_ratio <= 1);
assert.ok(Object.values(manualMetrics.view_metrics).every((view) => Number.isFinite(view.text_clarity)));

const triangle = geometry.triangles[0];
const surfaceCenter = [0, 1, 2].map((axis) => (triangle[0][axis] + triangle[1][axis] + triangle[2][axis]) / 3);
const penetrating = [{ id: 'penetration-probe', text: 'probe', anchor: surfaceCenter, center: surfaceCenter, boxSize: [bounds.radius * 0.03, bounds.radius * 0.02, bounds.radius * 0.005], bendPoints: [] }];
const penetrationMetrics = evaluateLayout(penetrating, bounds, { viewPolicy: 'binocular', depthGrids });
const simpleBasis = {right:[1,0,0],up:[0,1,0],forward:[0,0,1]};
const simpleLabel = {center:[0,0,0],boxSize:[1,1,0.02]};
assert.equal(triangleIntersectsLabelBox([[-1,0,0],[1,0,0],[0,1,0]],simpleLabel,simpleBasis),true);
assert.equal(triangleIntersectsLabelBox([[-1,0,2],[1,0,2],[0,1,2]],simpleLabel,simpleBasis),false);
assert.ok(penetrationMetrics.object_penetration_ratio > 0, 'surface probe must trigger the front/back depth-interval penetration proxy');
assert.equal(penetrationMetrics.penetration_method, 'five_view_front_back_depth_interval_proxy');
console.log('Multidimensional evaluator passed: shared camera, manual-style zero point, text metrics, and non-zero penetration probe.');
